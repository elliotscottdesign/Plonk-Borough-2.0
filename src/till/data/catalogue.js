// survives. Curated by hand from src/till/data/lightspeedLayout.json (the real
// 2025 export) against the CURRENT bar range (supabase/bar_seed.sql, 17 Aug 2026).
//
// The design rule (docs/till-decision.md §5): a till button is a SERVE of a
// stock product, never a product in its own right. Each item carries exactly
// one join into the bar lane's stock/cost engine:
//
//   stock:  'name'  — verbatim bar_products.name. Cost of a serve is then
//                     cost_per_base × ml (or × each) from the bar_cost_base view.
//   recipe: 'name'  — a bar_menu_items name (cocktails, food, anything mixed).
//                     GP comes from the bar_margins view once the recipe exists.
//   noStock: true   — sells time, not stock (golf, pool, tokens). 100% GP.
//   none of them    — an honest gap: the screen must say "no stock record",
//                     never guess. (House rule: never invent a price or cost.)
//
// price      = as actually rung in 2025 (the most-sold row for that serve).
//              null = a new line with no sales history — price not set yet.
// units2025  = 2025 units sold, duplicate till-buttons merged. Context, not
//              accounting — the true line-level record stays in the export.
//
// Prices are inc VAT. Nothing here is written anywhere — read-only catalogue.

